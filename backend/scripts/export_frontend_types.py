"""Generate field shapes from the actual FastAPI schemas, without exporting private operations."""
import json
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from app.api.application import create_app
from app.core.config import Settings
from app.core.graph import ROOT

def ts(schema):
    if '$ref' in schema: return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema: return ' | '.join(ts(s) for s in schema['anyOf'])
    if 'enum' in schema: return ' | '.join(json.dumps(v) for v in schema['enum'])
    kind=schema.get('type')
    if kind=='array': return f"Array<{ts(schema.get('items',{}))}>"
    if kind=='object':
        extra=schema.get('additionalProperties',{})
        return f"Record<string, {ts(extra) if isinstance(extra,dict) else 'unknown'}>"
    return {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(kind,'unknown')

def main():
    schemas=create_app(Settings(api_key='schema-export-only')).openapi()['components']['schemas']
    names=['NodeView','EdgeView','MapView','SurvivorView','ZombieView','ShelterView','VehicleView','StateView']
    lines=['// Generated by backend/scripts/export_frontend_types.py. Do not edit field shapes.','']
    for name in names:
        schema=schemas[name]
        lines.append(f'export interface {name} {{')
        for key,value in schema['properties'].items():
            optional='' if key in schema.get('required',[]) else '?'
            lines.append(f'  {key}{optional}: {ts(value)};')
        lines.extend(['}',''])
    output=ROOT/'frontend/src/types/generated.ts'
    output.parent.mkdir(parents=True,exist_ok=True)
    output.write_text('\n'.join(lines),encoding='utf-8')
    print(output)

if __name__=='__main__': main()
